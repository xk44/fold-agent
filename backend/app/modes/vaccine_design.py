# Multi-epitope construct builder
# ---------------------------------------------------------------------------

def build_multi_epitope_construct(
    epitopes: list[EpitopeCandidate],
    linker: str = "GPGPG",
    add_signal_peptide: bool = True,
) -> VaccineConstruct:
    """Concatenate epitope sequences with linkers into a multi-epitope construct.

    Optionally prepends the tPA signal peptide for secretory expression.
    Estimates molecular weight at 0.11 kDa per residue.
    """
    if not epitopes:
        raise ValueError("At least one epitope is required to build a construct.")

    linker_str = linker.upper() if isinstance(linker, str) else linker.value

    parts = [ep.sequence.upper() for ep in epitopes]
    joined = linker_str.join(parts)

    signal = _TPA_SIGNAL_PEPTIDE if add_signal_peptide else None
    full_sequence = (signal + joined) if signal else joined

    linkers_used = [linker_str] * (len(parts) - 1)

    total_length = len(full_sequence)
    estimated_mw = round(total_length * _AVG_RESIDUE_MW_KDA, 3)

    return VaccineConstruct(
        full_sequence=full_sequence,
        epitopes=epitopes,
        linkers=linkers_used,
        total_length=total_length,
        estimated_mw_kda=estimated_mw,
        signal_peptide=signal,
    )


