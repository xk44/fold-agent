def rapid_response_pipeline(
    pathogen_sequence: str,
    pathogen_name: str,
    top_n_epitopes: int = 5,
    linker: str = "GPGPG",
) -> dict:
    """End-to-end rapid-response vaccine design pipeline.

    Steps:
      1. Predict B-cell epitopes from sequence.
      2. Score epitopes by conservation (self-reference demo).
      3. Build multi-epitope construct from top N.
      4. Optimize mRNA construct.

    RESEARCH ONLY — not for clinical decision-making.
    """
    pipeline_start = time.monotonic()
    results: dict = {"pathogen_name": pathogen_name, "steps": {}, "disclaimer": VACCINE_DESIGN_DISCLAIMER}

    # Step 1: B-cell epitope prediction
    t0 = time.monotonic()
    b_cell_epitopes = predict_b_cell_epitopes(pathogen_sequence, top_n=top_n_epitopes)
    results["steps"]["b_cell_prediction"] = {
        "duration_s": round(time.monotonic() - t0, 4),
        "epitopes_found": len(b_cell_epitopes),
        "epitopes": [
            {
                "sequence": ep.sequence,
                "start": ep.start,
                "end": ep.end,
                "antigenicity_score": ep.antigenicity_score,
                "hydrophilicity": ep.hydrophilicity,
                "surface_accessibility": ep.surface_accessibility,
            }
            for ep in b_cell_epitopes
        ],
    }

    # Step 2: Conservation analysis (self-reference for demo)
    t0 = time.monotonic()
    conservation_results = []
    for ep in b_cell_epitopes:
        cr = analyze_epitope_conservation(ep.sequence, [pathogen_sequence])
        conservation_results.append(cr)
    results["steps"]["conservation_analysis"] = {
        "duration_s": round(time.monotonic() - t0, 4),
        "results": [
            {
                "sequence": cr.epitope_sequence,
                "conservation_score": cr.conservation_score,
                "strain_coverage": cr.strain_coverage,
                "variant_positions": cr.variant_positions,
            }
            for cr in conservation_results
        ],
    }

    # Step 3: Build multi-epitope construct
    t0 = time.monotonic()
    construct: VaccineConstruct | None = None
    construct_data: dict = {}
    if b_cell_epitopes:
        candidates = [
            EpitopeCandidate(
                sequence=ep.sequence,
                source=pathogen_name,
                epitope_type="b_cell",
                score=ep.antigenicity_score,
                conservation=cr.conservation_score,
            )
            for ep, cr in zip(b_cell_epitopes, conservation_results)
        ]
        construct = build_multi_epitope_construct(candidates, linker=linker)
        construct_data = {
            "full_sequence": construct.full_sequence,
            "total_length": construct.total_length,
            "estimated_mw_kda": construct.estimated_mw_kda,
            "linker": linker,
            "signal_peptide": construct.signal_peptide,
            "n_epitopes": len(construct.epitopes),
        }
    results["steps"]["construct_builder"] = {
        "duration_s": round(time.monotonic() - t0, 4),
        **construct_data,
    }

    # Step 4: mRNA optimization
    t0 = time.monotonic()
    mrna_data: dict = {}
    if construct:
        mrna = optimize_mrna_construct(construct.full_sequence)
        mrna_data = {
            "coding_sequence_length": len(mrna.coding_sequence),
            "gc_content": mrna.gc_content,
            "codon_adaptation_index": mrna.codon_adaptation_index,
            "poly_a_length": mrna.poly_a_length,
            "utr5_length": len(mrna.utr5),
            "utr3_length": len(mrna.utr3),
        }
    results["steps"]["mrna_optimization"] = {
        "duration_s": round(time.monotonic() - t0, 4),
        **mrna_data,
    }

    results["total_duration_s"] = round(time.monotonic() - pipeline_start, 4)
    return results


