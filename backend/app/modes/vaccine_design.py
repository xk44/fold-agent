def build_vaccine_design_report(
    case_id: str | None,
    epitopes: list[dict],
    db: "Session | None" = None,
) -> dict:
    """Build a structured vaccine design report.

    STRONG DISCLAIMER: Research only. Requires clinical trials, ethics board
    approval, and regulatory clearance. Not for human or animal use.
    """
    ep_candidates = [
        EpitopeCandidate(
            sequence=ep.get("sequence", ""),
            source=ep.get("source", "unknown"),
            epitope_type=ep.get("epitope_type", "b_cell"),
            score=float(ep.get("score", 0.0)),
            conservation=float(ep.get("conservation", 0.0)),
        )
        for ep in epitopes
        if ep.get("sequence")
    ]

    construct: VaccineConstruct | None = None
    mrna: mRNAConstruct | None = None

    if ep_candidates:
        construct = build_multi_epitope_construct(ep_candidates)
        mrna = optimize_mrna_construct(construct.full_sequence)

    case_info: dict = {}
    if case_id and db is not None:
        from backend.app.models import Case
        case = db.get(Case, case_id)
        if case:
            case_info = {
                "case_id": case_id,
                "species": case.species.value if hasattr(case.species, "value") else str(case.species),
                "id": case.id,
            }

    return {
        "report_type": "vaccine_design",
        "case_info": case_info,
        "disclaimers": [
            VACCINE_DESIGN_DISCLAIMER,
            "DO NOT USE FOR CLINICAL PURPOSES.",
            "All sequences are computational predictions only.",
            "Immunogenicity, safety, and efficacy have not been validated.",
            "Regulatory approval is required before any human or animal administration.",
        ],
        "construct": {
            "full_sequence": construct.full_sequence if construct else None,
            "total_length": construct.total_length if construct else 0,
            "estimated_mw_kda": construct.estimated_mw_kda if construct else 0.0,
            "signal_peptide": construct.signal_peptide if construct else None,
            "n_epitopes": len(ep_candidates),
        },
        "epitope_table": [
            {
                "sequence": ep.sequence,
                "source": ep.source,
                "epitope_type": ep.epitope_type,
                "score": ep.score,
                "conservation": ep.conservation,
            }
            for ep in ep_candidates
        ],
        "mrna_stats": {
            "coding_sequence_length": len(mrna.coding_sequence) if mrna else 0,
            "gc_content": mrna.gc_content if mrna else 0.0,
            "codon_adaptation_index": mrna.codon_adaptation_index if mrna else 0.0,
            "poly_a_length": mrna.poly_a_length if mrna else 0,
        },
    }
