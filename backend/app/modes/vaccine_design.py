def predict_b_cell_epitopes(
    protein_sequence: str,
    window_min: int = 12,
    window_max: int = 20,
    top_n: int = 5,
) -> list[BCellEpitope]:
    """Predict B-cell epitopes using sliding-window property scoring.

    Combines Parker hydrophilicity, Emini surface accessibility, and
    Kolaskar-Tongaonkar antigenicity. Returns top_n scored windows.

    STUB IMPLEMENTATION — not calibrated for clinical use.
    """
    seq = protein_sequence.upper()
    n = len(seq)
    if n < window_min:
        return []

    candidates: list[tuple[float, BCellEpitope]] = []

    window = (window_min + window_max) // 2  # fixed midpoint window for simplicity

    for i in range(n - window + 1):
        subseq = seq[i : i + window]

        hydro = sum(_safe_aa_lookup(PARKER_HYDROPHILICITY, aa) for aa in subseq) / window
        surf = sum(_safe_aa_lookup(EMINI_SURFACE_ACCESSIBILITY, aa) for aa in subseq) / window
        antig = sum(_safe_aa_lookup(_KOLASKAR_ANTIGENICITY, aa) for aa in subseq) / window

        # Combined score: high hydrophilicity + high surface + high antigenicity
        combined = (hydro + 3.4) / 6.8 * 0.4 + surf / 1.05 * 0.3 + (antig - 0.7) / 0.6 * 0.3

        epitope = BCellEpitope(
            start=i,
            end=i + window,
            sequence=subseq,
            surface_accessibility=round(surf, 4),
            hydrophilicity=round(hydro, 4),
            antigenicity_score=round(combined, 4),
        )
        candidates.append((combined, epitope))

    candidates.sort(key=lambda x: x[0], reverse=True)
    return [ep for _, ep in candidates[:top_n]]


