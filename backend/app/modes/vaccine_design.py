# Preferred codon tables (human and dog)
# Each amino acid maps to its most-preferred codon in that species
CODON_TABLES: dict[str, dict[str, str]] = {
    "human": {
        "A": "GCC", "R": "AGG", "N": "AAC", "D": "GAC", "C": "TGC",
        "Q": "CAG", "E": "GAG", "G": "GGC", "H": "CAC", "I": "ATC",
        "L": "CTG", "K": "AAG", "M": "ATG", "F": "TTC", "P": "CCC",
        "S": "AGC", "T": "ACC", "W": "TGG", "Y": "TAC", "V": "GTG",
        "*": "TGA",
    },
    "dog": {
        "A": "GCC", "R": "CGG", "N": "AAC", "D": "GAC", "C": "TGC",
        "Q": "CAG", "E": "GAG", "G": "GGC", "H": "CAC", "I": "ATC",
        "L": "CTG", "K": "AAG", "M": "ATG", "F": "TTC", "P": "CCC",
        "S": "TCC", "T": "ACC", "W": "TGG", "Y": "TAC", "V": "GTG",
        "*": "TGA",
    },
}

_UTR5_PLACEHOLDER = (
    "GGGAAAUAAGAGAGAAAAGAAGAGUAAGAAGAAAUAUAAGAGCCACCAUGGG"
)
_UTR3_PLACEHOLDER = (
    "UGCAUAAUAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA"
)
_DEFAULT_POLY_A_LENGTH = 120


def _reverse_translate(protein_sequence: str, species: str = "human") -> str:
    """Reverse-translate a protein sequence to coding DNA using preferred codons."""
    codon_table = CODON_TABLES.get(species.lower(), CODON_TABLES["human"])
    codons = []
    for aa in protein_sequence.upper():
        if aa in codon_table:
            codons.append(codon_table[aa])
        elif aa == "X":
            codons.append("NNN")  # unknown amino acid
        # skip gaps/non-standard
    return "".join(codons)


def _gc_content(sequence: str) -> float:
    """Calculate GC content of a nucleotide sequence (0-1)."""
    seq = sequence.upper()
    if not seq:
        return 0.0
    gc = sum(1 for nt in seq if nt in "GC")
    return round(gc / len(seq), 4)


def _estimate_cai(coding_sequence: str, species: str = "human") -> float:
    """Estimate codon adaptation index (simplified — ratio of preferred codons used)."""
    # Since we generate using preferred codons, CAI ≈ 1.0 for our output
    # Real CAI requires full codon usage table comparison
    codon_table = CODON_TABLES.get(species.lower(), CODON_TABLES["human"])
    preferred_codons = set(codon_table.values())
    seq = coding_sequence.upper()
    triplets = [seq[i : i + 3] for i in range(0, len(seq) - 2, 3)]
    if not triplets:
        return 0.0
    hits = sum(1 for c in triplets if c in preferred_codons)
    return round(hits / len(triplets), 4)


def optimize_mrna_construct(
    protein_sequence: str,
    species: str = "human",
    poly_a_length: int = _DEFAULT_POLY_A_LENGTH,
) -> mRNAConstruct:
    """Generate an mRNA construct from a protein sequence.

    Reverse-translates using preferred codons, adds 5'/3' UTR placeholders,
    and a poly-A tail.

    PLACEHOLDER — not calibrated for clinical manufacturing.
    """
    coding_seq = _reverse_translate(protein_sequence, species)
    # Add start codon if not already present
    if not coding_seq.startswith("ATG"):
        coding_seq = "ATG" + coding_seq
    # Add stop codon
    stop = CODON_TABLES.get(species.lower(), CODON_TABLES["human"]).get("*", "TGA")
    coding_seq = coding_seq + stop

    gc = _gc_content(coding_seq)
    cai = _estimate_cai(coding_seq, species)

    return mRNAConstruct(
        coding_sequence=coding_seq,
        utr5=_UTR5_PLACEHOLDER,
        utr3=_UTR3_PLACEHOLDER,
        poly_a_length=poly_a_length,
        gc_content=gc,
        codon_adaptation_index=cai,
    )


