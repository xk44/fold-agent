def analyze_epitope_conservation(
    epitope: str,
    reference_sequences: list[str],
    max_mismatches: int = 2,
) -> ConservationResult:
    """Analyse how conserved an epitope is across reference sequences.

    Checks exact match or ≤ max_mismatches substitutions using sliding window.
    """
    epitope_upper = epitope.upper()
    ep_len = len(epitope_upper)

    if not reference_sequences or ep_len == 0:
        return ConservationResult(
            epitope_sequence=epitope,
            conservation_score=0.0,
            variant_positions=[],
            strain_coverage=0.0,
        )

    hits = 0
    all_variant_positions: list[int] = []

    for ref in reference_sequences:
        ref_upper = ref.upper()
        best_mismatches = ep_len + 1  # worse than any real match
        best_variant_pos: list[int] = []

        for i in range(len(ref_upper) - ep_len + 1):
            window = ref_upper[i : i + ep_len]
            mismatches = sum(a != b for a, b in zip(epitope_upper, window))
            if mismatches < best_mismatches:
                best_mismatches = mismatches
                best_variant_pos = [j for j, (a, b) in enumerate(zip(epitope_upper, window)) if a != b]

        if best_mismatches <= max_mismatches:
            hits += 1
            all_variant_positions.extend(best_variant_pos)

    # Deduplicate variant positions
    unique_positions = sorted(set(all_variant_positions))
    strain_coverage = hits / len(reference_sequences)
    # Conservation score penalises variant positions
    if strain_coverage == 0.0:
        conservation_score = 0.0
    else:
        position_penalty = len(unique_positions) / ep_len * 0.3
        conservation_score = max(0.0, strain_coverage - position_penalty)

    return ConservationResult(
        epitope_sequence=epitope,
        conservation_score=round(conservation_score, 4),
        variant_positions=unique_positions,
        strain_coverage=round(strain_coverage, 4),
    )


