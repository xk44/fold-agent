_GROMACS_MDP_TEMPLATE = """\
; GROMACS .mdp — production MD — generated by FoldAgent MD Handoff
; RESEARCH ONLY — not for clinical decision-making.
; Force field : {force_field}
; Water model : {water_model}
; Temperature : {temperature_k} K
; Target run  : {simulation_ns} ns

; ── Run control ──────────────────────────────────────────────────────────────
integrator   = md
dt           = 0.002       ; 2 fs timestep
nsteps       = {nsteps}    ; {simulation_ns} ns total
comm-mode    = Linear
nstcomm      = 100

; ── Output ───────────────────────────────────────────────────────────────────
nstxout-compressed = 5000  ; ~10 ps between frames
nstlog       = 5000
nstenergy    = 500

; ── Neighbour list ───────────────────────────────────────────────────────────
cutoff-scheme = Verlet
nstlist       = 20
pbc           = xyz

; ── Electrostatics ───────────────────────────────────────────────────────────
coulombtype   = PME
rcoulomb      = 1.0

; ── van der Waals ─────────────────────────────────────────────────────────────
vdwtype       = Cut-off
rvdw          = 1.0
DispCorr      = EnerPres

; ── Temperature coupling ─────────────────────────────────────────────────────
tcoupl        = V-rescale
tc-grps       = Protein Non-Protein
tau-t         = 0.1 0.1
ref-t         = {temperature_k} {temperature_k}

; ── Pressure coupling ────────────────────────────────────────────────────────
pcoupl        = Parrinello-Rahman
pcoupltype    = isotropic
tau-p         = 2.0
ref-p         = 1.0
compressibility = 4.5e-5

; ── Constraints ──────────────────────────────────────────────────────────────
constraints   = h-bonds
constraint-algorithm = LINCS

; ── Velocity generation ──────────────────────────────────────────────────────
gen-vel       = no   ; velocities carried from NPT equilibration

; ──────────────────────────────────────────────────────────────────────────────
; Workflow reminder:
;   gmx pdb2gmx -f structure.pdb -o protein.gro -water {water_model}
;   gmx editconf -f protein.gro -o box.gro -c -d {box_padding_nm} -bt cubic
;   gmx solvate -cp box.gro -cs spc216.gro -o solvated.gro -p topol.top
;   gmx grompp -f ions.mdp -c solvated.gro -p topol.top -o ions.tpr
;   gmx genion -s ions.tpr -o ions.gro -p topol.top -pname NA -nname CL \\
;              -neutral -conc {ion_concentration_mol}
;   gmx grompp -f em.mdp  -c ions.gro   -p topol.top -o em.tpr
;   gmx mdrun  -v -deffnm em
;   gmx grompp -f nvt.mdp -c em.gro    -p topol.top -o nvt.tpr
;   gmx mdrun  -deffnm nvt
;   gmx grompp -f npt.mdp -c nvt.gro   -p topol.top -o npt.tpr
;   gmx mdrun  -deffnm npt
;   gmx grompp -f {mdp_name} -c npt.gro -p topol.top -o md.tpr
;   gmx mdrun  -deffnm md
"""


def export_for_gromacs(pdb_data: str, config: MDExportConfig) -> MDExportResult:
    """Export a PDB structure as a GROMACS .mdp parameter file.

    Parameters
    ----------
    pdb_data:
        PDB-format string of the structure to simulate.
    config:
        Simulation parameters.

    Returns
    -------
    MDExportResult with a GROMACS .mdp file as ``config_script``.

    RESEARCH ONLY — not for clinical or regulatory decision-making.
    """
    warnings: list[str] = []

    supported_ff = {"amber14", "charmm36"}
    if config.force_field not in supported_ff:
        warnings.append(f"Force field '{config.force_field}' may not be bundled with GROMACS. "
                        "Use 'amber14' or 'charmm36'.")

    nsteps = int(config.simulation_ns * 1_000 / 0.002)
    mdp_name = "md_production.mdp"

    mdp = _GROMACS_MDP_TEMPLATE.format(
        force_field=config.force_field,
        water_model=config.water_model,
        box_padding_nm=config.box_padding_nm,
        ion_concentration_mol=config.ion_concentration_mol,
        temperature_k=config.temperature_k,
        simulation_ns=config.simulation_ns,
        nsteps=nsteps,
        mdp_name=mdp_name,
    )

    # Runtime estimate: ~50 ns/day on a 4-GPU cluster for ~300-residue protein
    estimated_runtime = round(config.simulation_ns / 50.0 * 24.0, 1)

    topology_data = (
        "; GROMACS topology placeholder\n"
        "; Run pdb2gmx to generate the actual topol.top and position restraint files.\n"
        f"; Force field: {config.force_field}  Water: {config.water_model}\n"
    )
    coordinate_data = pdb_data if pdb_data.strip() else "; No PDB data provided.\n"

    return MDExportResult(
        format="gromacs",
        topology_data=topology_data,
        coordinate_data=coordinate_data,
        config_script=mdp,
        estimated_runtime_hours=estimated_runtime,
        warnings=warnings,
    )


