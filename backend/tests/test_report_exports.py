def test_scan_clean_text_returns_empty() -> None:
    clean = "This is a research coordination artifact listing candidate antigens."
    findings = scan_for_unsafe_content(clean)
    assert findings == []


def test_scan_detects_dosage_pattern() -> None:
    text = "Administer 50 mg dose to the subject subcutaneously."
    findings = scan_for_unsafe_content(text)
    assert len(findings) >= 1
    assert any(f["severity"] == "high" for f in findings)


def test_scan_detects_injection_pattern() -> None:
    text = "inject into subcutaneous tissue using a sterile needle."
    findings = scan_for_unsafe_content(text)
    assert len(findings) >= 1
    assert any("inject" in f["matched_text"].lower() for f in findings)


def test_scan_detects_treatment_protocol() -> None:
    text = "treatment protocol: administer peptide vaccine every 3 weeks."
    findings = scan_for_unsafe_content(text)
    assert len(findings) >= 1


def test_scan_returns_recommendation(text: str = "Administer 10 ml injection") -> None:
    findings = scan_for_unsafe_content(text)
    if findings:
        assert all("recommendation" in f for f in findings)
        assert all("severity" in f for f in findings)
        assert all("matched_text" in f for f in findings)


def test_scan_does_not_duplicate_overlapping_matches() -> None:
    """Overlapping matches should not produce duplicate entries."""
    text = "inject into the patient subcutaneous tissue now"
    findings = scan_for_unsafe_content(text)
    matched_spans = [(f["matched_text"], f["pattern"]) for f in findings]
    # No two entries should have the same matched_text+pattern combination
    assert len(matched_spans) == len(set(matched_spans))


def test_scan_dose_equals_pattern() -> None:
    text = "dose=50 should be rejected"
    findings = scan_for_unsafe_content(text)
    assert len(findings) >= 1


def test_scan_manufacturing_protocol_pattern() -> None:
    text = "Follow the manufacturing protocol steps carefully."
    findings = scan_for_unsafe_content(text)
    assert len(findings) >= 1
    assert any(f["severity"] == "moderate" for f in findings)


