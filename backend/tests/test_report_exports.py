def _make_case(client: TestClient, species: str = "demo", summary: str = "Export test") -> str:
    resp = client.post("/cases", json={"species": species, "diagnosis_summary": summary})
    assert resp.status_code == 201
    return resp.json()["id"]


def _make_case_with_candidates(client: TestClient, species: str = "demo") -> tuple[str, list[str]]:
    case_id = _make_case(client, species=species)
    for sample_type in ("tumor", "normal", "rna"):
        client.post(f"/cases/{case_id}/samples", json={"sample_type": sample_type})
    variant_ids = []
    for i in range(2):
        v = client.post(
            f"/cases/{case_id}/variants",
            json={"genomic_coordinates": f"chr{i + 1}:1000:A>T", "gene": f"GENE{i}"},
        )
        assert v.status_code == 201
        variant_ids.append(v.json()["id"])
    candidate_ids = []
    for vid in variant_ids:
        c = client.post(
            f"/cases/{case_id}/candidates",
            json={
                "variant_id": vid,
                "prediction_scores": {"binding_affinity": 80.0, "rank": 0.8},
                "expression_evidence": {"tpm": 10.5},
                "mhc_context": "HLA-A*02:01",
            },
        )
        assert c.status_code == 201
        candidate_ids.append(c.json()["id"])
    return case_id, candidate_ids


